def cell_rows(rows: list[str]) -> list[str]:
    w = len(rows[0])
    if len(rows) == 11:
        return rows
    pad_top = ["." * w] * 2
    if len(rows) == 7:
        return pad_top + rows + ["." * w] * 2
    if len(rows) == 9:
        return pad_top + rows
    raise ValueError(f"altezza glifo non valida: {len(rows)}")


def build(out_dir: Path, name: str = "tactica") -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    chars = sorted(G.keys(), key=ord)
    widths = {c: len(G[c][0]) for c in chars}
    cols = 16
    cw = max(widths.values()) + 1
    rows_n = (len(chars) + cols - 1) // cols
    img = Image.new("RGBA", (cols * cw, rows_n * H), (0, 0, 0, 0))
    px = img.load()
    lines = [
        f'info face="Tactica Pixel" size={H} bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=1,1',
        f"common lineHeight={H + 2} base={BASE} scaleW={img.width} scaleH={img.height} pages=1 packed=0",
        f'page id=0 file="{name}.png"',
        f"chars count={len(chars)}",
    ]
    for i, c in enumerate(chars):
        x0, y0 = (i % cols) * cw, (i // cols) * H
        rows = cell_rows(G[c])
        for y, row in enumerate(rows):
            assert len(row) == widths[c], f"riga di larghezza diversa in {c!r}"
            for x, v in enumerate(row):
                if v == "#":
                    px[x0 + x, y0 + y] = (255, 255, 255, 255)
        adv = widths[c] + 1
        lines.append(
            f"char id={ord(c)} x={x0} y={y0} width={widths[c]} height={H} xoffset=0 yoffset=0 xadvance={adv} page=0 chnl=15"
        )
    img.save(out_dir / f"{name}.png")
    (out_dir / f"{name}.fnt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{name}.fnt: {len(chars)} glifi, atlante {img.size}")


def preview(path: str, text: str = "Tactica · Guerra fra clan «Lupi» → Vittoria! È già ora: però più città, 120% ★") -> None:
    scale = 4
    x = 0
    total = sum(len(cell_rows(G.get(c, G["?"]))[0]) + 1 for c in text)
    img = Image.new("RGBA", (total * scale + 8, (H + 2) * scale), (24, 26, 40, 255))
    for c in text:
        rows = cell_rows(G.get(c, G["?"]))
        for y, row in enumerate(rows):
            for xx, v in enumerate(row):
                if v == "#":
                    for dy in range(scale):
                        for dx in range(scale):
                            img.putpixel((4 + (x + xx) * scale + dx, (y + 1) * scale + dy), (245, 235, 210, 255))
        x += len(rows[0]) + 1
    img.save(path)


