GRAVE = [".#.", "..#"]
ACUTE = ["..#", ".#."]


def accented(base: str, accent: list[str]) -> list[str]:
    """Minuscola accentata: l'accento nelle prime due righe (area ascendenti)."""
    rows = [r for r in G[base]]
    w = len(rows[0])
    off = max(0, (w - 3) // 2)
    for i in range(2):
        line = list(rows[i])
        for j, ch in enumerate(accent[i]):
            if ch == "#" and off + j < w:
                line[off + j] = "#"
        rows[i] = "".join(line)
    return rows


def accented_cap(base: str, accent: list[str]) -> list[str]:
    rows = G[base]
    w = len(rows[0])
    off = max(0, (w - 3) // 2)
    top = []
    for i in range(2):
        line = ["."] * w
        for j, ch in enumerate(accent[i]):
            if ch == "#" and off + j < w:
                line[off + j] = "#"
        top.append("".join(line))
    return top + rows + ["." * w, "." * w]


